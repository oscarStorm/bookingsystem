"""Idempotent demo seed for the MVP (PRD2 §11 seed dataset).

Run from backend/:  python -m scripts.seed

Creates the Demo Restaurant dataset: 1 restaurant (Europe/Copenhagen,
30-day horizon), booking rules, opening hours Tue–Sun (Monday closed — no
row), 2 enclaves, 7 tables with allocation priorities, and 1 admin staff
user. Running it multiple times never creates duplicates.

The admin password is read from the SEED_ADMIN_PASSWORD environment variable
by main() — it is never hardcoded here or committed.
"""

from datetime import time

from argon2 import PasswordHasher
from sqlalchemy import select, text
from sqlalchemy.orm import Session

from app.config.settings import get_settings
from app.database.session import get_session_factory
from app.models import (
    BookingRules,
    OpeningHours,
    Restaurant,
    RestaurantTable,
    StaffUser,
    TableEnclave,
)

RESTAURANT_ID = 1
ADMIN_EMAIL = "admin@demo-restaurant.example"

# (table_number, capacity, enclave_id, allocation_priority)
TABLES = [
    (1, 4, None, 40),
    (2, 2, None, 10),
    (3, 2, 1, 30),
    (4, 2, 1, 31),
    (5, 2, 1, 32),
    (6, 2, 2, 20),
    (7, 2, 2, 21),
]

# day_of_week 0 = Monday … 6 = Sunday; Monday is closed (no row)
OPENING_HOURS = [(day, time(17, 30), time(21, 0), time(0, 0)) for day in range(1, 7)]


def _get_or_create(session: Session, model, defaults: dict | None = None, **filters):
    instance = session.scalar(select(model).where(*[getattr(model, k) == v for k, v in filters.items()]))
    if instance is not None:
        return instance
    instance = model(**(filters | (defaults or {})))
    session.add(instance)
    return instance


def seed(session: Session, admin_password: str | None = None) -> None:
    """Insert the demo dataset if missing. Idempotent. Raises ValueError if the
    staff user does not exist yet and no admin password was supplied."""
    restaurant = _get_or_create(
        session,
        Restaurant,
        defaults=dict(name="Demo Restaurant", timezone="Europe/Copenhagen", booking_horizon_days=30),
        id=RESTAURANT_ID,
    )

    _get_or_create(
        session,
        BookingRules,
        defaults=dict(
            slot_interval_minutes=15,
            reservation_duration_minutes=120,
            buffer_minutes=15,
            max_online_party_size=6,
            first_seating_start=time(17, 30),
            first_seating_last_start=time(18, 15),
            max_seatings_per_table=2,
        ),
        restaurant_id=restaurant.id,
    )

    for day, open_t, kitchen_close_t, close_t in OPENING_HOURS:
        _get_or_create(
            session,
            OpeningHours,
            defaults=dict(open_time=open_t, kitchen_close_time=kitchen_close_t, close_time=close_t),
            restaurant_id=restaurant.id,
            day_of_week=day,
        )

    for enclave_pk, name in [(1, "Enclave 1"), (2, "Enclave 2")]:
        _get_or_create(
            session, TableEnclave, defaults=dict(name=name), id=enclave_pk, restaurant_id=restaurant.id
        )

    for number, capacity, enclave_id, priority in TABLES:
        _get_or_create(
            session,
            RestaurantTable,
            defaults=dict(capacity=capacity, enclave_id=enclave_id, allocation_priority=priority, is_active=True),
            restaurant_id=restaurant.id,
            table_number=number,
        )

    staff = session.scalar(select(StaffUser).where(StaffUser.email == ADMIN_EMAIL))
    if staff is None:
        if not admin_password:
            raise ValueError(
                "SEED_ADMIN_PASSWORD environment variable is required to create "
                "the initial staff account; no password is hardcoded."
            )
        staff = StaffUser(
            restaurant_id=restaurant.id,
            name="Admin",
            email=ADMIN_EMAIL,
            password_hash=PasswordHasher().hash(admin_password),  # Argon2id
            role="admin",
            is_active=True,
        )
        session.add(staff)

    session.commit()
    # Fixed ids were inserted into GENERATED BY DEFAULT identity columns;
    # advance the sequences so later inserts cannot collide.
    for table in ("restaurants", "table_enclaves"):
        session.execute(
            text(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"COALESCE((SELECT MAX(id) FROM {table}), 1))"
            )
        )
    session.commit()


def main() -> None:
    settings = get_settings()
    session = get_session_factory()()
    try:
        seed(session, admin_password=settings.seed_admin_password)
        print("Seed OK: Demo Restaurant dataset present (idempotent).")
    finally:
        session.close()


if __name__ == "__main__":
    main()
